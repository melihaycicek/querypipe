import { products } from "@/lib/demo-schema";
import { CodeBlock } from "@/components/code-block";
import { QueryTokenString } from "@/components/query-token-string";
import { SpecJson } from "@/components/spec-json";

/**
 * Server-side story. The left pane is the Express handler (mirrors
 * examples/express-prisma). The right pane is NOT typed by hand: this is a
 * server component, so `products.parse(...)` runs the real package at build
 * time and the JSON below is its actual output.
 */

const BAD_REQUEST = "sort=price:desc&filter=price:like:5&limit=abc";

const EXPRESS_CODE = `import express from "express";
import { createQuery, dateField, enumField, isErr, numberField, stringField } from "querypipe";

const products = createQuery({
  fields: {
    id: numberField(),
    name: stringField(),
    price: numberField(),
    category: enumField(["phone", "laptop", "tablet"]),
    deletedAt: dateField(),
  },
  stableBy: "id",
  guards: { maxSortColumns: 3 },
});

const app = express();

app.get("/products", async (req, res) => {
  const parsed = products.parse(req.originalUrl.split("?")[1] ?? "");

  if (isErr(parsed)) {
    // Structured, machine-readable 400 — no try/catch anywhere.
    res.status(400).json({ ok: false, errors: parsed.errors });
    return;
  }

  // parsed.value is whitelisted, guard-limited and injection-safe by
  // construction. Map it to your ORM by hand for now — official adapters
  // (@querypipe/prisma, @querypipe/sql) ship in v0.2.
  const rows = await db.product.findMany(toPrismaArgs(parsed.value));
  res.json({ ok: true, rows });
});`;

export function ServerStory() {
  // Real output, produced at build time by the real package.
  const parsed = products.parse(BAD_REQUEST);

  return (
    <div className="grid gap-4 lg:grid-cols-2">
      <CodeBlock code={EXPRESS_CODE} lang="ts" title="server.ts — Express" />
      <div className="panel flex min-w-0 flex-col overflow-hidden">
        <div className="border-b border-line px-3 py-1.5">
          <p className="truncate font-mono text-xs text-ink-muted">
            GET /products?<QueryTokenString value={BAD_REQUEST} className="text-xs" />
          </p>
        </div>
        <div className="border-b border-line px-3 py-1.5">
          <p className="font-mono text-xs">
            <span className="text-tok-err">HTTP/1.1 400</span>
            <span className="text-ink-muted"> · content-type: application/json</span>
          </p>
        </div>
        <div className="min-h-0 flex-1 overflow-auto p-3">
          <SpecJson value={parsed} />
        </div>
        <p className="border-t border-line px-3 py-1.5 text-[11px] text-ink-muted">
          This response body is generated by running <code className="font-mono">parse</code> at
          build time — not typed by hand.
        </p>
      </div>
    </div>
  );
}
